#!/usr/bin/env python3
"""Idea bank for the DrumR idea engine.

  bank.py sync              Rebuild ideas-bank.md from every run in output/.
  bank.py status <run-dir>  Print the loop state of one run as JSON.

The bank is regenerated from the run artifacts (scorecard.md, challenge-*.md,
project-start-*.yaml, ideas.md), so it never drifts from them. Anything below
the "## Notes" heading in ideas-bank.md is kept as-is.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "output"
BANK = ROOT / "ideas-bank.md"
THESIS = ROOT / "founder" / "thesis.md"

ROW_RE = re.compile(
    r"^\|\s*(\d+)\s*\|\s*(IDEA-\d{2,})\s*\|\s*(.+?)\s*\|\s*([\d.]+)\s*\|\s*([\d.]+)\s*\|"
    r"\s*([\d.]+)\s*\|\s*\**([\d.]+)\**\s*\|\s*\**\s*(Advance|Iterate|Park)\b",
    re.M,
)
FINAL_RE = re.compile(r"Final Verdict.*?Composite:\s*([\d.]+).*?Gate:\s*(Advance|Iterate|Park)", re.S)
HEADING_RE = re.compile(r"^##+\s*(IDEA-\d{2,})\b.*$", re.M)


def scorecard_rows(run: Path):
    sc = run / "scorecard.md"
    if not sc.exists():
        return []
    rows, seen = [], set()
    for m in ROW_RE.finditer(sc.read_text()):
        idea = m.group(2)
        if idea in seen:
            continue
        seen.add(idea)
        rows.append({
            "id": idea, "title": m.group(3).strip(),
            "d": m.group(4), "v": m.group(5), "f": m.group(6),
            "composite": float(m.group(7)), "gate": m.group(8),
        })
    return rows


def idea_fields(run: Path):
    """Signals and Parent per idea, from ideas.md."""
    path = run / "ideas.md"
    out = {}
    if not path.exists():
        return out
    text = path.read_text()
    heads = list(HEADING_RE.finditer(text))
    for i, h in enumerate(heads):
        body = text[h.end(): heads[i + 1].start() if i + 1 < len(heads) else len(text)]
        sig = re.search(r"\*\*Signals:\*\*\s*(.+)", body)
        par = re.search(r"\*\*Parent:\*\*\s*(.+)", body)
        out[h.group(1)] = {
            "signals": ", ".join(re.findall(r"SIG-\d+", sig.group(1))) if sig else "",
            "parent": (re.search(r"IDEA-\d{2,}", par.group(1)).group(0)
                       if par and re.search(r"IDEA-\d{2,}", par.group(1)) else ""),
        }
    return out


def challenge(run: Path, idea: str):
    path = run / f"challenge-{idea}.md"
    if not path.exists():
        return None
    m = FINAL_RE.search(path.read_text())
    return {"composite": float(m.group(1)), "gate": m.group(2)} if m else {"composite": None, "gate": "?"}


def run_state(run: Path):
    fields = idea_fields(run)
    ideas = []
    for r in scorecard_rows(run):
        ch = challenge(run, r["id"])
        handed = (run / f"project-start-{r['id']}.yaml").exists()
        if handed:
            status = "Handed off"
        elif ch:
            status = f"{ch['gate']} (challenged)"
        else:
            status = r["gate"]
        ideas.append({**r, **fields.get(r["id"], {"signals": "", "parent": ""}),
                      "challenge": ch, "handed_off": handed, "status": status})
    return ideas


def target():
    if THESIS.exists():
        m = re.search(r"Target:\s*\**(\d+)", THESIS.read_text())
        if m:
            return int(m.group(1))
    return 10


def sync():
    runs = sorted(p for p in OUTPUT.iterdir() if p.is_dir()) if OUTPUT.exists() else []
    lines, handed, advance_ready = [], 0, 0
    for run in runs:
        for i in run_state(run):
            handed += i["handed_off"]
            ok = i["challenge"] and i["challenge"]["gate"] == "Advance" and not i["handed_off"]
            advance_ready += bool(ok)
            ch = i["challenge"]
            lines.append(
                f"| {run.name} | {i['id']} | {i['title']} | {i['composite']:.2f} | {i['gate']} | "
                f"{(str(ch['composite']) + ' ' + ch['gate']) if ch else '—'} | {i['status']} | "
                f"{i['signals'] or '—'} | {i['parent'] or '—'} |"
            )
    notes = ""
    if BANK.exists():
        old = BANK.read_text()
        if "\n## Notes" in old:
            notes = old[old.index("\n## Notes"):].lstrip("\n")
    if not notes:
        notes = "## Notes\n\nFree-form notes. This section is kept when the bank is rebuilt.\n"
    out = [
        "# Idea bank",
        "",
        "> Generated by `scripts/bank.py sync` from every run in `output/`. Do not edit",
        "> the table by hand — edit the run artifacts and re-sync.",
        "",
        f"**Handed off to P/S Fitter: {handed} / {target()}** · "
        f"challenged Advance awaiting handoff: {advance_ready} · ideas scored: {len(lines)}",
        "",
        "| Run | ID | Title | Composite | Gate | Challenge | Status | Signals | Parent |",
        "|-----|----|-------|:---:|------|------|--------|---------|--------|",
        *lines,
        "",
        notes,
    ]
    BANK.write_text("\n".join(out))
    print(f"ideas-bank.md: {len(lines)} ideas from {len(runs)} runs; handed off {handed}/{target()}")


def unused_signals(run: Path):
    sig, ideas = run / "signals.md", run / "ideas.md"
    if not sig.exists():
        return []
    defined = re.findall(r"^##+\s*(SIG-\d+)", sig.read_text(), re.M)
    cited = set(re.findall(r"SIG-\d+", ideas.read_text())) if ideas.exists() else set()
    return [s for s in defined if s not in cited]


def status(run_dir: str):
    run = Path(run_dir)
    if not run.is_absolute():
        run = ROOT / run
    ideas = run_state(run)
    nums = [int(i["id"].split("-")[1]) for i in ideas]
    ideas_md = run / "ideas.md"
    if ideas_md.exists():
        nums += [int(x) for x in re.findall(r"IDEA-(\d{2,})", ideas_md.read_text())]
    reframed = {i["parent"] for i in ideas if i["parent"]}
    by = lambda g: [i["id"] for i in sorted(ideas, key=lambda x: -x["composite"]) if i["gate"] == g]
    state = {
        "advance": by("Advance"),
        "advance_unchallenged": [x for x in by("Advance")
                                 if not next(i for i in ideas if i["id"] == x)["challenge"]],
        "challenged_advance": [i["id"] for i in ideas
                               if i["challenge"] and i["challenge"]["gate"] == "Advance"],
        "iterate_not_reframed": [x for x in by("Iterate") if x not in reframed],
        "park": by("Park"),
        "handed_off": [i["id"] for i in ideas if i["handed_off"]],
        "next_free_id": f"IDEA-{(max(nums) if nums else 0) + 1:02d}",
        "unused_signals": unused_signals(run),
    }
    print(json.dumps(state, indent=2))


if __name__ == "__main__":
    if len(sys.argv) >= 2 and sys.argv[1] == "sync":
        sync()
    elif len(sys.argv) >= 3 and sys.argv[1] == "status":
        status(sys.argv[2])
    else:
        print(__doc__)
        sys.exit(2)
